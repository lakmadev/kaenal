// Maps the design kit's icon names (project_brain/mobile/src/*) to lucide icons —
// lucide is what the web app uses, so the mark set matches pixel-for-pixel. Adding a
// new screen that references an unlisted name is a typecheck error (the union below),
// which keeps the map honest.
