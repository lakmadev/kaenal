export type IconName = keyof typeof ICONS;

export interface IconProps {
  name: IconName;
  size?: number;
  /** Stroke width (design kit uses ~1.9 for body, 2.2–2.4 for emphasis). */
  stroke?: number;
  /** Explicit color; defaults to the current text color. */
  color?: string;
}

export function Icon({ name, size = 18, stroke = 1.9, color }: IconProps) {
  const { palette } = useTheme();
  const Glyph = ICONS[name];
  return <Glyph size={size} strokeWidth={stroke} color={color ?? palette.text} />;
}
